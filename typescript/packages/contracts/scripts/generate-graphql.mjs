// Generate TypeScript types for the GraphQL query side from contracts/graphql/schema.graphql (CTR-005).
// The output records the schema's SHA-256, so a test can prove the client was generated from the
// committed schema. SDP_GRAPHQL_OUT overrides the output path (used by drift checks).
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  buildSchema,
  isEnumType,
  isInputObjectType,
  isListType,
  isNonNullType,
  isObjectType,
  isScalarType,
} from "graphql";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../../..");
const schemaPath = path.join(root, "contracts/graphql/schema.graphql");
const out = process.env.SDP_GRAPHQL_OUT ?? path.resolve(here, "../src/graphql/generated.ts");

const sdl = fs.readFileSync(schemaPath, "utf8");
const schema = buildSchema(sdl);
const SCALARS = { ID: "string", String: "string", Int: "number", Float: "number", Boolean: "boolean", JSON: "unknown" };

function ts(type) {
  if (isNonNullType(type)) return inner(type.ofType);
  return `${inner(type)} | null`;
}
function inner(type) {
  if (isListType(type)) {
    const item = ts(type.ofType);
    return item.includes("|") ? `Array<${item}>` : `${item}[]`;
  }
  if (isScalarType(type)) return SCALARS[type.name] ?? "unknown";
  return type.name;
}

const lines = [
  "// Generated by scripts/generate-graphql.mjs from contracts/graphql/schema.graphql. Do not edit.",
  "",
  `export const SCHEMA_SHA256 = "${createHash("sha256").update(sdl).digest("hex")}";`,
  "",
];
const types = Object.values(schema.getTypeMap())
  .filter((t) => !t.name.startsWith("__"))
  .sort((a, b) => a.name.localeCompare(b.name));
for (const type of types) {
  if (isObjectType(type) || isInputObjectType(type)) {
    if (type.description) lines.push(`/** ${type.description} */`);
    lines.push(`export interface ${type.name} {`);
    for (const field of Object.values(type.getFields())) {
      if (field.description) lines.push(`  /** ${field.description} */`);
      const optional = !isNonNullType(field.type) ? "?" : "";
      lines.push(`  ${field.name}${optional}: ${ts(field.type)};`);
    }
    lines.push("}", "");
    if (isObjectType(type)) {
      for (const field of Object.values(type.getFields())) {
        if (!field.args.length) continue;
        const name = `${type.name}${field.name[0].toUpperCase()}${field.name.slice(1)}Args`;
        lines.push(`export interface ${name} {`);
        for (const arg of field.args) {
          const optional = !isNonNullType(arg.type) || arg.defaultValue !== undefined ? "?" : "";
          lines.push(`  ${arg.name}${optional}: ${ts(arg.type)};`);
        }
        lines.push("}", "");
      }
    }
  } else if (isEnumType(type)) {
    lines.push(`export type ${type.name} = ${type.getValues().map((v) => JSON.stringify(v.name)).join(" | ")};`, "");
  }
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), out)}`);
